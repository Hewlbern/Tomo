"""Derive v3 drive geometry from first principles and write v3_params.scad (included by the .scad).
Frame: z up, -y = face, +y = wearer/strap side. Pre-mirror frame = the +x arm (arm_L = critter's own LEFT).
arm_R (critter's RIGHT, -x) is built in the same pre-mirror frame and mirrored in x."""
import numpy as np, json
import os
os.chdir(os.path.dirname(os.path.abspath(__file__)) + "/..")
Cd=np.array([0,20.0]); Cp=np.array([58,10.0])
cord_d=0.5
r_d=10.0+cord_d/2        # drum groove bottom r10 (v1 drum) -> cord centreline r
r_q=7.75+cord_d/2        # arm pulley groove bottom r7.75 -> centreline r8.0
th_c=45.0; th_stop_c=46.0; th_stop_o=-3.0
root_local=-20.0         # direction the arm root leaves the hub, arm-local (open pose) deg
def unit(a): return np.array([np.cos(np.radians(a)),np.sin(np.radians(a))])
def ang(v): return float(np.degrees(np.arctan2(v[1],v[0])))
# L (+x): internal tangent: drum below its centre, pulley above its centre
D=Cd-Cp; a0=ang(D); b=np.degrees(np.arccos((r_d+r_q)/np.linalg.norm(D)))
nL=[unit(a0+s*b) for s in (1,-1)]; nL=[n for n in nL if n[1]>0][0]
dL=Cd-r_d*nL; pL=Cp+r_q*nL
# R (pre-mirror): external top tangent: tangent points C + r n
b2=np.degrees(np.arccos((r_q-r_d)/np.linalg.norm(D)))
nR=[unit(a0+s*b2) for s in (1,-1)]; nR=[n for n in nR if n[1]>0][0]
dR=Cd+r_d*nR; pR=Cp+r_q*nR
out={}
for side,dp,pp in (("L",dL,pL),("R",dR,pR)):
    phi_t=ang(pp-Cp)                    # pulley tangent angle (world, fixed)
    root_closed=root_local+th_c
    anchor_closed=root_closed+18.2+13.0 if side=="R" else phi_t-23.0
    out[side]=dict(drum_pt=dp.tolist(),pulley_pt=pp.tolist(),phi_t=phi_t,drum_phi=ang(dp-Cd),
        anchor_local=anchor_closed-th_c, wrap_closed=phi_t-anchor_closed, wrap_open=phi_t-(anchor_closed-th_c),
        free_len_xy=float(np.linalg.norm(pp-dp)))
# winding / torque sign checks (pre-mirror frame for R: closing = CCW there; mirrored later)
def surf_vel(p,omega=-1): r=p-Cd; return omega*np.array([-r[1],r[0]])
chk={}
for side in "LR":
    o=out[side]; dp=np.array(o["drum_pt"]); pp=np.array(o["pulley_pt"])
    dp_w=dp*np.array([-1,1]) if side=="R" else dp     # real world drum point for R
    pp_w=pp*np.array([-1,1]) if side=="R" else pp
    pulled_in=float(surf_vel(dp_w)@(pp_w-dp_w))<0     # CW drum surface moves away from free cord
    F=(dp-pp)/np.linalg.norm(dp-pp); r=pp-Cp; tz=r[0]*F[1]-r[1]*F[0]   # pre-mirror: + = CCW = closing
    chk[side]=dict(drum_CW_pulls_in=pulled_in, closing_moment_arm_mm=round(float(tz),3))
out["checks"]=chk
# stop pillars (bracket, pre-mirror local = world-relative-to-pivot): root contacts pillar at stop
rp=14.5; half=np.degrees(np.arcsin((2.5+1.5)/rp))
out["pillar_close_ang"]=root_local+th_stop_c+half; out["pillar_open_ang"]=root_local+th_stop_o-half
out.update(r_d=r_d,r_q=r_q,th_c=th_c,th_stop_c=th_stop_c,th_stop_o=th_stop_o,root_local=root_local,pillar_r=rp,
           drum_ratio_deg_per_deg=r_q/r_d, drum_wrap_open_deg=40.0)
# drum anchors (drum frame at clasp=0): wound arc runs CW from tangent point
out["drum_anchor_L"]=out["L"]["drum_phi"]-40.0; out["drum_anchor_R"]=(180-out["R"]["drum_phi"])-40.0  # R real-world tangent angle = 180-phi (mirror)
json.dump(out,open("results/design_params.json","w"),indent=1)
f=open("cad/v3_params.scad","w")
f.write("// GENERATED by scripts/design_params.py - do not hand edit\n")
for k in ["r_d","r_q","th_c","th_stop_c","th_stop_o","root_local","pillar_r"]: f.write(f"{k}={out[k]:.4f};\n")
f.write(f"pillar_close_ang={out['pillar_close_ang']:.4f}; pillar_open_ang={out['pillar_open_ang']:.4f};\n")
f.write(f"drum_ratio={r_q/r_d:.6f};\n")
for s in "LR":
    o=out[s]; f.write(f"anchor_local_{s}={o['anchor_local']:.4f}; phi_t_{s}={o['phi_t']:.4f};\n")
    f.write(f"drum_pt_{s}=[{o['drum_pt'][0]:.4f},{o['drum_pt'][1]:.4f}]; pulley_pt_{s}=[{o['pulley_pt'][0]:.4f},{o['pulley_pt'][1]:.4f}];\n")
f.write(f"drum_anchor_L={out['drum_anchor_L']:.4f}; drum_anchor_R={out['drum_anchor_R']:.4f};\n")
f.close()
# FS90MG drum is 1:1 on the horn. Travel for 0-45 deg clasp:
travel=float(np.radians(th_c)*r_q)
psi=float(np.degrees(travel/r_d))
stop_travel=float(np.radians(th_stop_c-th_stop_o)*r_q)
stop_psi=float(np.degrees(stop_travel/r_d))
out["clasp_to_drum"]=dict(r_d=r_d,r_q=r_q,travel_0_to_45_mm=round(travel,4),
    drum_deg_0_to_45=round(psi,4),servo_deg_0_to_45=round(psi,4),  # 1:1 horn mount
    travel_stop_to_stop_mm=round(stop_travel,4),drum_deg_stop_to_stop=round(stop_psi,4),
    within_180=bool(stop_psi<180), ratio=r_q/r_d,
    note="Drum xy unchanged from v2; clasp_top lowered to 51 so grooves still straddle zq=63.5 after the 4.0 mm horn gap. Fleet ±1.8 deg.")
json.dump(out,open("results/design_params.json","w"),indent=1)
print(json.dumps(out,indent=1))
